"""Stretch goals that re-use a finished run's eval set:
- compare: factory-made agent vs a hand-written (human) baseline, case by case.
- regress: documents changed -> regenerate the agent from the saved requirements, re-run the OLD eval set, and
  separate genuine regressions from cases whose ground truth no longer exists in the new documents."""
from __future__ import annotations

import json
from pathlib import Path

from .agent_runtime import AgentRuntime
from .generator import generate_agent
from .ingest import load_folder
from .judge import Judge
from .llm import LLM
from .pipeline import make_scorecard
from .report import _pct
from .schemas import AgentDefinition, CaseResult, EvalCase, Requirements
from .textmatch import fact_in


def _load_run(run: Path):
    cases = [EvalCase.model_validate(c) for c in json.loads((run / "evalset.json").read_text(encoding="utf-8"))]
    agent = AgentDefinition.model_validate_json((run / "agent.json").read_text(encoding="utf-8"))
    req = Requirements.model_validate_json((run / "requirements.json").read_text(encoding="utf-8"))
    return cases, agent, req


def _final_results(run: Path) -> dict[str, dict]:
    scs = json.loads((run / "scorecards.json").read_text(encoding="utf-8"))
    log = json.loads((run / "iteration_log.json").read_text(encoding="utf-8"))
    best_it = max((c["iteration"] for c in log if c.get("kept")), default=0)
    sc = next(s for s in scs if s["iteration"] == best_it)
    return {r["case_id"]: r for r in sc["results"]}


def evaluate(defn: AgentDefinition, cases: list[EvalCase], llm: LLM, judge: Judge | None = None) -> list[CaseResult]:
    rt = AgentRuntime(defn, llm)
    judge = judge or Judge(llm)
    out = []
    for c in cases:
        tr = rt.ask(c.question)
        out.append(judge.grade(c, tr, rt.context_text(tr)))
    return out


def compare_baseline(run: Path, baseline_path: Path, llm: LLM) -> dict:
    cases, factory, _ = _load_run(run)
    human = AgentDefinition.model_validate_json(baseline_path.read_text(encoding="utf-8"))
    human.docs_path = factory.docs_path  # same documents, same eval set; only the definition differs
    llm.trace_path, llm.stage = run / "trace_compare.jsonl", "compare"
    judge = Judge(llm)
    f_sc = make_scorecard(-1, evaluate(factory, cases, llm, judge))
    h_sc = make_scorecard(-1, evaluate(human, cases, llm, judge))
    hp = {r.case_id: r for r in h_sc.results}
    fp = {r.case_id: r for r in f_sc.results}
    factory_wins = [i for i in fp if fp[i].passed and not hp[i].passed]
    human_wins = [i for i in fp if not fp[i].passed and hp[i].passed]
    out = {"factory": {"overall": f_sc.overall_pass_rate, "by_kind": f_sc.by_kind, "failures": f_sc.failures},
           "human": {"overall": h_sc.overall_pass_rate, "by_kind": h_sc.by_kind, "failures": h_sc.failures},
           "factory_wins": factory_wins, "human_wins": human_wins}
    by_id = {c.id: c for c in cases}
    md = ["# Factory vs human baseline", "",
          "Same documents, same generated eval set, same judge; only the agent definition differs.", "",
          "| Case type | Factory | Human |", "|---|---|---|"]
    md += [f"| {k} | {_pct(f_sc.by_kind[k])} | {_pct(h_sc.by_kind.get(k, 0))} |" for k in f_sc.by_kind]
    md += [f"| **overall** | **{_pct(f_sc.overall_pass_rate)}** | **{_pct(h_sc.overall_pass_rate)}** |", "",
           f"## Where the factory wins ({len(factory_wins)})"]
    md += [f"- {i} [{by_id[i].kind}] {by_id[i].question} - human: {'; '.join(hp[i].notes) or hp[i].failure}"
           for i in factory_wins] or ["- none"]
    md += ["", f"## Where the human wins ({len(human_wins)})"]
    md += [f"- {i} [{by_id[i].kind}] {by_id[i].question} - factory: {'; '.join(fp[i].notes) or fp[i].failure}"
           for i in human_wins] or ["- none"]
    md += ["", "Caveat: the eval set was generated by the factory's own pipeline, which may favour the factory's framing."]
    (run / "baseline_comparison.json").write_text(json.dumps(out, indent=2), encoding="utf-8")
    (run / "baseline_comparison.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    return out


def regress(run: Path, new_docs: Path, llm: LLM, out: Path) -> dict:
    cases, old_agent, req = _load_run(run)
    old_results = _final_results(run)
    out.mkdir(parents=True, exist_ok=True)
    llm.trace_path, llm.stage = out / "trace.jsonl", "regress"
    docs, _ = load_folder(new_docs)
    texts = {d.id: " ".join(d.text.split()) for d in docs}
    by_stem = {Path(k).stem: v for k, v in texts.items()}  # leave_policy.pdf -> leave_policy.md still matches

    def facts_still_true(c: EvalCase) -> bool:
        if not c.key_facts:
            return True
        pool = " ".join(texts.get(s) or by_stem.get(Path(s).stem, "") for s in c.expected_sources) or " ".join(texts.values())
        return all(fact_in(f, pool) for f in c.key_facts)

    regenerated, _ = generate_agent(req, docs, llm, str(Path(new_docs).resolve()), old_agent.name + "-regenerated", 1,
                                    (run / "brief.md").read_text(encoding="utf-8") if (run / "brief.md").exists() else "")
    new_agent = regenerated[0]
    new_agent.retrieval = old_agent.retrieval.model_copy()  # keep the tuned retrieval; regenerate the prompt
    (out / "agent.json").write_text(new_agent.model_dump_json(indent=2), encoding="utf-8")
    rows = []
    for r in evaluate(new_agent, cases, llm):
        c = next(x for x in cases if x.id == r.case_id)
        was = old_results.get(r.case_id, {}).get("passed")
        stale = not facts_still_true(c)
        if was and not r.passed:
            status = "eval_stale" if stale else "REGRESSION"
        elif not was and r.passed:
            status = "improved"
        else:
            status = ("unchanged_pass" if r.passed else "unchanged_fail") + ("_stale" if stale else "")
        rows.append({"case_id": r.case_id, "kind": r.kind, "question": c.question, "was": was, "now": r.passed,
                     "status": status, "notes": r.notes})
    summary = {s: sum(x["status"] == s for x in rows) for s in sorted({x["status"] for x in rows})}
    (out / "regression.json").write_text(json.dumps({"summary": summary, "cases": rows}, indent=2), encoding="utf-8")
    md = ["# Regression report", "", f"Old run: `{run}` -> new documents: `{new_docs}`", "",
          "The old eval set was re-run against an agent regenerated from the saved requirements. A case whose key "
          "facts no longer appear in the new documents is marked *stale*: the test is out of date, not the agent.", "",
          "| Status | Cases |", "|---|---|"] + [f"| {k} | {v} |" for k, v in summary.items()]
    md += ["", "## Details"] + [f"- **{x['case_id']}** {x['status']}: {x['question']}"
                                + (f" - {'; '.join(x['notes'])}" if x["notes"] and not x["now"] else "")
                                for x in rows if x["status"] != "unchanged_pass"]
    (out / "regression.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    return summary
